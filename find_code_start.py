"""
Find valid 6800 code sequences by analyzing opcodes
"""

# Known 6800 opcodes
KNOWN_OPCODES = {
    0x01, 0x06, 0x07, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F,
    0x19, 0x1B, 0x20, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28,
    0x29, 0x2A, 0x2B, 0x2C, 0x2D, 0x2E, 0x2F, 0x39, 0x3E, 0x3F,
    0x81, 0x82, 0x84, 0x85, 0x86, 0x88, 0x89, 0x8A, 0x8B, 0x8D,
    0x90, 0x91, 0x92, 0x94, 0x95, 0x96, 0x97, 0x98, 0x99, 0x9A,
    0x9B, 0x9C, 0x9D, 0x9E, 0x9F,
    0xA0, 0xA1, 0xA2, 0xA4, 0xA5, 0xA6, 0xA7, 0xA8, 0xA9, 0xAA,
    0xAB, 0xAC, 0xAD, 0xAE, 0xAF,
    0xB0, 0xB1, 0xB2, 0xB3, 0xB4, 0xB5, 0xB6, 0xB7, 0xB8, 0xB9,
    0xBA, 0xBB, 0xBC, 0xBD, 0xBE, 0xBF,
    0xC1, 0xC2, 0xC4, 0xC5, 0xC6, 0xC8, 0xC9, 0xCA, 0xCB,
    0xD0, 0xD1, 0xD2, 0xD4, 0xD5, 0xD6, 0xD7, 0xD8, 0xD9, 0xDA,
    0xDB, 0xDC, 0xDD, 0xDE, 0xDF,
    0xE0, 0xE1, 0xE2, 0xE4, 0xE5, 0xE6, 0xE7, 0xE8, 0xE9, 0xEA,
    0xEB, 0xEC, 0xED, 0xEE, 0xEF,
    0xF0, 0xF1, 0xF2, 0xF3, 0xF4, 0xF5, 0xF6, 0xF7, 0xF8, 0xF9,
    0xFA, 0xFB, 0xFC, 0xFD, 0xFE,
}

def count_valid_opcodes(data, offset, length=100):
    """Count valid opcodes in a region"""
    count = 0
    i = 0
    while i < length and offset + i < len(data):
        if data[offset + i] in KNOWN_OPCODES:
            count += 1
        i += 1
    return count

with open('eliza_side_b.bin', 'rb') as f:
    data = f.read()

print('=== FINDING VALID 6800 CODE REGIONS ===\n')

# Score different starting positions
scores = []

# Check every position in first 2KB
for offset in range(0x2000):
    score = count_valid_opcodes(data, offset, 50)
    if score >= 10:  # At least 10/50 bytes are valid opcodes
        scores.append((score, offset))

# Sort by score
scores.sort(reverse=True)

print('Top 20 potential code starts (by opcode frequency):')
for score, offset in scores[:20]:
    percentage = (score / 50) * 100
    
    # Show first 32 bytes
    seg_data = data[offset:offset+32]
    hex_str = ' '.join(f'{b:02X}' for b in seg_data)
    
    print(f'0x{offset:05X}: Score {score}/50 ({percentage:.0f}%) - {hex_str}')

print()
print(f'\n=== KNOWN SEGMENTS ===')
print('Segment 1: 0x00000-0x00068 (105 bytes) - possible bootloader')
print('Segment 6: 0x000C7-0x005CC (1286 bytes)')
print('Segment 81: 0x12DB-0x07B2B (26,705 bytes) - MAIN PROGRAM')

print()
print('=== CHECKING KNOWN SEGMENTS ===')
for name, start, end in [
    ('Segment 1 (bootloader)', 0x00000, 0x00069),
    ('Segment 6', 0x000C7, 0x005CD),
    ('Segment 81 (main)', 0x12DB, 0x07B30),
]:
    if start < len(data):
        score = count_valid_opcodes(data, start, min(50, end - start))
        pct = (score / 50) * 100 if (end - start) >= 50 else (score / (end - start)) * 100
        print(f'{name}: {score} valid opcodes in first {min(50, end-start)} bytes ({pct:.0f}%)')
